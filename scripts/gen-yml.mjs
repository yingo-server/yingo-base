// Generate yingotab.yml from apps/*/app.json and music/ directory.
// Node 22 native ESM, zero dependencies.
import { readdirSync, readFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

const esc = (s) => String(s).replace(/'/g, "''");

// ---- apps ----
const apps = [];
const appsDir = join(ROOT, 'apps');
if (existsSync(appsDir)) {
  for (const dir of readdirSync(appsDir, { withFileTypes: true })) {
    if (!dir.isDirectory()) continue;
    const jsonPath = join(appsDir, dir.name, 'app.json');
    if (existsSync(jsonPath)) {
      try {
        apps.push(JSON.parse(readFileSync(jsonPath, 'utf8')));
        continue;
      } catch (e) {
        console.error(`Warning: failed to parse ${jsonPath}: ${e.message}`);
      }
    }
    // fallback: use directory name
    apps.push({
      id: dir.name,
      name: dir.name,
      icon: '📦',
      type: 'dock',
      entry: `apps/${dir.name}/index.html`,
    });
  }
}

// ---- music ----
const music = [];
let musicMeta = {};
const musicJson = join(ROOT, 'music', 'music.json');
if (existsSync(musicJson)) {
  try { musicMeta = JSON.parse(readFileSync(musicJson, 'utf8')); } catch (e) { musicMeta = {}; }
}
const musicDir = join(ROOT, 'music');
if (existsSync(musicDir)) {
  for (const f of readdirSync(musicDir, { withFileTypes: true })) {
    if (!f.isFile()) continue;
    if (!/\.(mp3|m4a|ogg|flac|wav|aac)$/i.test(f.name)) continue;
    const meta = musicMeta[f.name] || {};
    music.push({ title: meta.title ?? f.name, file: `music/${f.name}` });
  }
}

// ---- widgets: none ----
const widgets = [];

// ---- emit YAML (hand-joined, single-quote escaping) ----
const lines = [];
lines.push('# generated by CI, do not edit');
lines.push('version: 1');
lines.push('apps:');
if (apps.length === 0) lines.push('  []');
for (const a of apps) {
  lines.push(`  - id: '${esc(a.id)}'`);
  lines.push(`    name: '${esc(a.name)}'`);
  lines.push(`    icon: '${esc(a.icon)}'`);
  lines.push(`    type: '${esc(a.type)}'`);
  lines.push(`    entry: '${esc(a.entry)}'`);
}
lines.push('music:');
if (music.length === 0) lines.push('  []');
for (const m of music) {
  lines.push(`  - title: '${esc(m.title)}'`);
  lines.push(`    file: '${esc(m.file)}'`);
}
lines.push('widgets: []');

const out = lines.join('\n') + '\n';
const outPath = join(ROOT, 'yingotab.yml');
if (existsSync(outPath) && readFileSync(outPath, 'utf8') === out) {
  console.log('yingotab.yml is up to date.');
} else {
  process.stdout.write(out);
  if (process.env.CI) {
    const { writeFileSync } = await import('node:fs');
    writeFileSync(outPath, out);
    console.error('Wrote yingotab.yml');
  } else {
    writeFileSync(outPath, out);
    console.error('Wrote yingotab.yml');
  }
}
